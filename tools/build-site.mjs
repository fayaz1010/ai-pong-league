// Bundle the players, league results and brick-breaker scores into docs/data.js, so the site
// works on GitHub Pages and straight from file:// with no fetches. Run after changing players/:
//   npm run build
import fs from 'node:fs'; import path from 'node:path'; import {fileURLToPath} from 'node:url';
import {NAMES, listTeams} from '../league/teams.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const json = (p) => JSON.parse(read(p));
const MODELS = {
  'GPT-6 Astra': {maker: 'OpenAI', logo: 'logos/openai_blossom_mark_white.svg', color: '#3fd6a4'},
  'Fable 5.1': {maker: 'Anthropic', logo: 'logos/claude_spark.svg', color: '#e8875f'},
  'Opus 5.5': {maker: 'Anthropic', logo: 'logos/claude_spark.svg', color: '#f2b36b'},
  'Gemini': {maker: 'Google', logo: 'logos/gemini_sparkle.svg', color: '#6f9cff', full: 'Gemini 4 Argon'},
  'Grok 4.7': {maker: 'xAI', logo: 'logos/grok_mark_white.svg', color: '#e6e6e6'},
};

const teams = listTeams().map((t) => {
  const meta = fs.existsSync(t.file.replace(/\.js$/, '.json')) ? JSON.parse(fs.readFileSync(t.file.replace(/\.js$/, '.json'), 'utf8')) : {};
  return {id: t.id, model: t.model, code: fs.readFileSync(t.file, 'utf8'), file: path.relative(ROOT, t.file),
    cost: meta.usage ? +meta.usage.cost.toFixed(4) : null, seconds: meta.seconds ? Math.round(meta.seconds) : null,
    tokens: meta.usage ? meta.usage.completion_tokens : null};
});

const league = json('league/league.json');
const games = league.games.map((g) => [g.home, g.away, g.seed, g.score, g.frames]);

function bricks(round) {
  const dir = `bench/brick-breaker/round${round}/runs`; const out = [];
  for (const [folder, model] of Object.entries(NAMES)) for (const n of [1, 2, 3]) {
    const t = json(`${dir}/${folder}/${n}.test.json`); const m = json(`${dir}/${folder}/${n}.json`);
    out.push({model, attempt: n, file: `brick-breaker/round${round}/${folder}-${n}.html`, passed: t.passed, total: t.total,
      cost: +m.usage.cost.toFixed(4), seconds: Math.round(m.seconds)});
  }
  return out;
}

const sum = (a) => a.reduce((s, x) => s + (x || 0), 0);
const testRoundCost = sum(fs.readdirSync(path.join(ROOT, 'test-round/players')).flatMap((d) => [1, 2, 3].map((n) => {
  const f = `test-round/players/${d}/${n}.json`; return fs.existsSync(path.join(ROOT, f)) ? json(f).usage.cost : 0; })));
const b1 = bricks(1), b2 = bricks(2);
const costs = {pong: sum(teams.map((t) => t.cost)), pongTest: testRoundCost, brick1: sum(b1.map((b) => b.cost)), brick2: sum(b2.map((b) => b.cost))};
costs.total = costs.pong + costs.pongTest + costs.brick1 + costs.brick2;
for (const k in costs) costs[k] = +costs[k].toFixed(2);

const data = {models: MODELS, teams, rows: league.rows, byModel: league.byModel, games, bricks: {round1: b1, round2: b2}, costs,
  spec: read('league/SPEC4.md'), video: 'https://youtu.be/7GJfxWFiFDI', repo: 'https://github.com/fayaz1010/ai-pong-league'};
fs.writeFileSync(path.join(ROOT, 'docs/data.js'), '// Generated by tools/build-site.mjs from players/ and league/league.json. Do not edit by hand.\nwindow.LEAGUE = ' + JSON.stringify(data) + ';\n');
console.log(`docs/data.js: ${teams.length} players, ${games.length} games, ${b1.length + b2.length} brick breakers, model cost $${costs.total} (`
  + `pong $${costs.pong}, pong test round $${costs.pongTest}, brick r1 $${costs.brick1}, brick r2 $${costs.brick2}), ${(fs.statSync(path.join(ROOT, 'docs/data.js')).size / 1024).toFixed(0)} KB`);
